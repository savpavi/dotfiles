#!/usr/bin/env python3
"""Hyprland settings the savpavi-shell settings window can change.

Values live in config/hypr/settings.json; config/hypr/settings.lua is generated
from it (required at the end of hyprland.lua). Every change is checked with
`Hyprland --verify-config` first; on failure the previous files are restored.

  get                          JSON: settings + live monitors (+ modes) + idle timeout
  set-layout KEY=VAL ...       gaps_in gaps_out border_size rounding
  set-input KEY=VAL ...        repeat_rate repeat_delay sensitivity natural_scroll
  set-monitors JSON            full monitor list [{output, mode, position, scale, transform}]
  bind-set FILE LINE KEY       change the key of the hl.bind on FILE:LINE
  bind-add KEY NAME CMD        add a custom shortcut (user-binds.json -> user-binds.lua)
  bind-remove N                remove custom shortcut N
  idle-set SECONDS             lock after SECONDS idle (0 = never); restarts hypridle
"""
import json, re, shutil, subprocess as sp, sys, tempfile
from pathlib import Path

HYPR = Path.home() / "dotfiles/config/hypr"
SETTINGS = HYPR / "settings.json"
LUA = HYPR / "settings.lua"
UBINDS = HYPR / "user-binds.json"
ULUA = HYPR / "user-binds.lua"
IDLE = HYPR / "hypridle.conf"


def load(path, default):
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return default


def lua_str(s):
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def render_settings(cfg):
    L, I = cfg["layout"], cfg["input"]
    out = ["-- Generated by savpavi-shell settings (scripts/hypr-settings.py) from settings.json.",
           "-- Edit the JSON or use the settings window (Super+Alt+S); this file is rewritten.", "",
           "hl.config({",
           "    general = {",
           f"        gaps_in = {int(L['gaps_in'])},",
           f"        gaps_out = {int(L['gaps_out'])},",
           f"        border_size = {int(L['border_size'])},",
           "        resize_on_border = false,",
           "    },",
           f"    decoration = {{ rounding = {int(L['rounding'])} }},",
           "    input = {",
           f"        repeat_rate = {int(I['repeat_rate'])},",
           f"        repeat_delay = {int(I['repeat_delay'])},",
           f"        sensitivity = {float(I['sensitivity'])},",
           f"        touchpad = {{ natural_scroll = {'true' if I['natural_scroll'] else 'false'} }},",
           "    },",
           "})", ""]
    for m in cfg["monitors"]:
        out.append("hl.monitor({")
        out.append(f"    output = {lua_str(m['output'])},")
        out.append(f"    mode = {lua_str(m['mode'])},")
        out.append(f"    position = {lua_str(m['position'])},")
        out.append(f"    scale = {m['scale']},")
        out.append(f"    transform = {int(m.get('transform', 0))},")
        out.append("})")
    out += ["", "-- the bar shows the wallpaper behind it, not the windows",
            'hl.layer_rule({ match = { namespace = "^savpavi-bar$" }, xray = true })', ""]
    return "\n".join(out)


def render_binds(binds):
    out = ["-- Custom shortcuts from the savpavi-shell settings window (user-binds.json).", ""]
    for b in binds:
        out.append(f"hl.bind({lua_str(b['key'])}, hl.dsp.exec_cmd({lua_str(b['cmd'])}))  -- {b['name']}")
    return "\n".join(out) + "\n"


def apply(files):
    """files: {path: new_text}. Write, verify, reload; restore on failure."""
    backup = {p: (p.read_text() if p.exists() else None) for p in files}
    for p, text in files.items():
        p.write_text(text)
    r = sp.run(["Hyprland", "--verify-config"], capture_output=True, text=True)
    if r.returncode != 0 or "config ok" not in r.stdout + r.stderr:
        for p, old in backup.items():
            if old is None:
                p.unlink(missing_ok=True)
            else:
                p.write_text(old)
        sys.exit("config doğrulanmadı, geri alındı:\n" + (r.stdout + r.stderr)[-800:])
    sp.run(["hyprctl", "reload", "config-only"], capture_output=True)
    errs = sp.run(["hyprctl", "configerrors"], capture_output=True, text=True).stdout.strip()
    if errs:
        print("uyarı: " + errs, file=sys.stderr)


def idle_get():
    m = re.search(r'listener\s*\{\s*timeout\s*=\s*(\d+)\s*\n\s*on-timeout\s*=\s*loginctl lock-session', IDLE.read_text())
    return int(m.group(1)) if m else 0


def main():
    cmd, args = (sys.argv[1] if len(sys.argv) > 1 else "get"), sys.argv[2:]
    cfg = load(SETTINGS, None)
    if cfg is None:
        sys.exit("settings.json yok")

    if cmd == "get":
        live = json.loads(sp.run(["hyprctl", "monitors", "all", "-j"], capture_output=True, text=True).stdout or "[]")
        print(json.dumps({**cfg, "idle": idle_get(), "custom_binds": load(UBINDS, []),
                          "live": [{k: m.get(k) for k in ("name", "description", "make", "model", "serial", "width", "height",
                                                         "refreshRate", "x", "y", "scale", "transform", "availableModes",
                                                         "focused", "disabled", "physicalWidth", "physicalHeight")}
                                   for m in live]}, ensure_ascii=False))
        return

    if cmd in ("set-layout", "set-input"):
        sect = "layout" if cmd == "set-layout" else "input"
        for kv in args:
            k, v = kv.split("=", 1)
            if k not in cfg[sect]:
                sys.exit(f"bilinmeyen ayar: {k}")
            old = cfg[sect][k]
            cfg[sect][k] = (v.lower() == "true") if isinstance(old, bool) else type(old)(float(v)) if isinstance(old, (int, float)) else v
        SETTINGS.write_text(json.dumps(cfg, indent=2, ensure_ascii=False) + "\n")
        apply({LUA: render_settings(cfg)})
        return

    if cmd == "set-monitors":
        old_json = SETTINGS.read_text()
        cfg["monitors"] = json.loads(args[0])
        SETTINGS.write_text(json.dumps(cfg, indent=2, ensure_ascii=False) + "\n")
        try:
            apply({LUA: render_settings(cfg)})
        except SystemExit:
            SETTINGS.write_text(old_json)
            raise
        return

    if cmd == "bind-set":
        path, line, key = Path(args[0]), int(args[1]), args[2]
        lines = path.read_text().splitlines(keepends=True)
        src = lines[line - 1]
        new = re.sub(r'hl\.bind\((.+?),(?=\s*(hl\.dsp|function))', lambda m: 'hl.bind(' + lua_str(key) + ',', src, count=1)
        if new == src:
            sys.exit("satırdaki kısayol değiştirilemedi")
        lines[line - 1] = new
        apply({path: "".join(lines)})
        return

    if cmd in ("bind-add", "bind-remove"):
        binds = load(UBINDS, [])
        if cmd == "bind-add":
            binds.append({"key": args[0], "name": args[1], "cmd": args[2]})
        else:
            binds.pop(int(args[0]))
        UBINDS.write_text(json.dumps(binds, indent=2, ensure_ascii=False) + "\n")
        apply({ULUA: render_binds(binds)})
        return

    if cmd == "idle-set":
        secs = int(args[0])
        text = IDLE.read_text()
        block = re.compile(r'#?\s*listener\s*\{\s*\n\s*#?\s*timeout\s*=\s*\d+\s*\n\s*#?\s*on-timeout\s*=\s*loginctl lock-session\s*\n\s*#?\s*\}', re.M)
        repl = (f"listener {{\n    timeout = {secs}\n    on-timeout = loginctl lock-session\n}}" if secs > 0 else
                "# listener {\n#     timeout = 600\n#     on-timeout = loginctl lock-session\n# }")
        if not block.search(text):
            sys.exit("hypridle.conf içinde kilit dinleyicisi bulunamadı")
        IDLE.write_text(block.sub(repl, text, count=1))
        sp.run(["pkill", "-x", "hypridle"])
        sp.Popen(["setsid", "-f", "hypridle"], stdout=sp.DEVNULL, stderr=sp.DEVNULL)
        return

    sys.exit(__doc__)


if __name__ == "__main__":
    main()
